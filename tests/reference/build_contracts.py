def output_row(row: dict[str, Any]) -> dict[str, Any]:
    schema = {k: v for k, v in row.items() if k not in {"name", "value_type"}}
    return {"name": row["name"], "value_type": value_type(schema), "schema": schema}


def composite_input_rows(spec: dict[str, Any]) -> list[dict[str, Any]]:
    rows = []
    for item in spec["inputs"]:
        schema = {k: v for k, v in item.items() if k not in {"name", "required"}}
        widget = "text"
        if item["type"] == "integer":
            widget = "integer"
        elif item["type"] == "boolean":
            widget = "boolean"
        elif item["type"] == "array":
            widget = "multi_select" if item["items"].get("enum") else "json"
        elif item.get("enum"):
            widget = "select"
        rows.append(
            {
                "name": item["name"],
                "required": bool(item.get("required")),
                "schema": schema,
                "widget": widget,
                "options": item.get("enum") or item.get("items", {}).get("enum"),
            }
        )
    return rows


def manifest_rows(reg: dict[str, Any]) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for spec in composite_specs.COMPOSITES:
        rows.append(
            {
                "id": spec["operation_id"],
                "title": spec["title"],
                "description": spec["description"],
                "kind": spec["kind"],
                "inputs": composite_input_rows(spec),
                "outputs": spec["outputs"],
                "area": "Everyday",
                "calls": spec["calls"],
            }
        )
    for sid, entry in reg["operations"].items():
        rows.append(
            {
                "id": sid,
                "title": entry["title"],
                "description": entry["description"],
                "kind": entry["kind"],
                "inputs": step_inputs(entry),
                "outputs": generic_outputs(entry),
                "area": entry["area"],
                "calls": [entry["shown"]],
            }
        )
    return rows


def operation_manifest(rows: list[dict[str, Any]]) -> dict[str, Any]:
    ops = []
    for row in rows:
        write = row["kind"] == "write"
        inputs = [{"name": "connection_ref", "value_type": "connection_ref", "required": True}]
        for item in row["inputs"]:
            inputs.append(
                {
                    "name": item["name"],
                    "value_type": value_type(item["schema"]),
                    "required": item["required"],
                    "schema": item["schema"],
                }
            )
        op: dict[str, Any] = {
            "operation_id": row["id"],
            "display_name": row["title"],
            "description": row["description"],
            "operation_kind": "action" if write else "source",
            "category": "marketing",
            "connection_type_ids": [CONNECTION_TYPE],
            "workflow_visible": True,
        }
        if write:
            op["effect_kind"] = f"threads_{row['id']}"
        outputs = [output_row(o) for o in row["outputs"]]
        op.update(
            inputs=inputs,
            outputs=outputs,
            result_fields=[f"result.{o['name']}" for o in outputs],
            error_codes=ERROR_CODES_WRITE if write else ERROR_CODES_READ,
        )
        ops.append(op)
    return {"operations": ops}


def step_ui_manifest(rows: list[dict[str, Any]]) -> dict[str, Any]:
    forms = []
    for row in rows:
        fields = []
        for item in row["inputs"]:
            label, help_text = field_texts.text_of(item["name"], item["schema"].get("description"))
            field: dict[str, Any] = {
                "name": item["name"],
                "label": label,
                "widget_type": item["widget"],
                "required": item["required"],
                "help_text": help_text[:400],
            }
            if item.get("options"):
                field["options"] = [{"label": v, "value": v} for v in item["options"]]
            if item["widget"] == "json":
                field["placeholder"] = "[]" if item["schema"].get("type") == "array" else "{}"
            fields.append(field)
        forms.append({"operation_id": row["id"], "title": row["title"], "fields": fields})
    return {"forms": forms}


def actions_manifest(rows: list[dict[str, Any]]) -> dict[str, Any]:
    actions = []
    for row in rows:
        write = row["kind"] == "write"
        action: dict[str, Any] = {
            "action_id": row["id"],
            "title": row["title"],
            "description": row["description"],
            "required_scopes": ["extension:invoke"],
            "handler": {"mode": "extension"},
        }
        if write:
            action["command_type"] = "invoke_extension_action"
        action.update(
            mutates_platform=write,
            workflow_visible=True,
            parameters=[{"name": "connection_ref", "type": "connection_ref", "required": True}]
            + [
                {
                    "name": i["name"],
                    "type": value_type(i["schema"])
                    if value_type(i["schema"]) != "text"
                    else "string",
                    "required": i["required"],
                }
                for i in row["inputs"]
            ],
            result_fields=[o["name"] for o in row["outputs"]],
            error_codes=ERROR_CODES_WRITE if write else ERROR_CODES_READ,
        )
        actions.append(action)
    return {"actions": actions}


