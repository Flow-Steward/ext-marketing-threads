def schema_of(n: dict[str, Any], *, title: str, description: str) -> dict[str, Any]:
    kind = n["kind"]
    schema: dict[str, Any]
    if kind == "integer":
        schema = {"type": "integer", **{k: n[k] for k in ("minimum", "maximum") if k in n}}
    elif kind == "decimal":
        schema = {"type": ["number", "string"]}
    elif kind == "boolean":
        schema = {"type": "boolean"}
    elif kind in {"names", "id_list", "codes"}:
        items: dict[str, Any] = {"type": "string"}
        if n.get("allowed"):
            items["enum"] = n["allowed"]
        schema = {"type": "array", "items": items}
        if kind == "id_list":
            schema.update(minItems=n["min_items"], maxItems=n["max_items"])
    elif kind == "object":
        schema = {"type": "object", "additionalProperties": True}
    elif kind == "url":
        schema = {"type": "string", "maxLength": 2000}
    elif kind == "moment":
        schema = {"type": ["string", "integer"]}
    elif kind == "id":
        schema = {"type": "string", "maxLength": 30}
    else:
        schema = {"type": "string", "maxLength": n["max_length"]}
        if n.get("allowed"):
            schema["enum"] = n["allowed"]
    schema["title"] = title
    if description:
        schema["description"] = description[:600]
    return schema


def widget_for(n: dict[str, Any]) -> str:
    kind = n["kind"]
    if kind == "integer":
        return "integer"
    if kind == "boolean":
        return "boolean"
    if kind in {"names", "codes", "id_list"}:
        return "multi_select" if n.get("allowed") else "json"
    if kind == "object":
        return "json"
    if n.get("allowed"):
        return "select"
    return "text"


def value_type(schema: dict[str, Any]) -> str:
    kind = schema.get("type")
    if isinstance(kind, list):
        kinds = [k for k in kind if k != "null"]
        if len(kinds) != 1:
            return "text"
        kind = kinds[0]
    return {"integer": "integer", "boolean": "boolean", "array": "array", "object": "object"}.get(
        str(kind), "text"
    )


def step_inputs(entry: dict[str, Any]) -> list[dict[str, Any]]:
    rows = []
    for prm in entry["params"]:
        n = prm["node"]
        title = LABELS.get(prm["name"], prm["name"])
        words = prm["description"]
        if prm["name"] == "threads-user-id":
            words = "The Threads user ID, or me for the connected account (the default)."
        if prm["name"] in {"image_url", "video_url"}:
            words += (
                " Threads takes media only from a public URL, which it downloads itself; a "
                "workflow file must first be published at a public URL."
            )
        if n["kind"] == "moment":
            words += " A Unix timestamp or a date such as 2026-01-01."
        if n["kind"] in {"names", "codes", "id_list"}:
            words += " Give a list; it is sent comma-separated."
        if n["kind"] == "object":
            words += " Give a JSON object; it is sent as JSON text."
        rows.append(
            {
                "name": prm["input"],
                "required": n["required"],
                "schema": schema_of(n, title=title, description=words),
                "widget": widget_for(n),
                "options": n.get("allowed"),
            }
        )
    if entry["paged"]:
        rows += [
            {
                "name": "all_pages",
                "required": False,
                "schema": {
                    "type": "boolean",
                    "title": "All pages",
                    "description": "True to read every page from after (or the start) until the list ends.",
                },
                "widget": "boolean",
            },
            {
                "name": "max_items",
                "required": False,
                "schema": {
                    "type": "integer",
                    "minimum": 1,
                    "maximum": 100000,
                    "title": "At most",
                    "description": "With all_pages: the most records to read. Default 10000.",
                },
                "widget": "integer",
            },
        ]
    return rows


