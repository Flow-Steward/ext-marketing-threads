def facts() -> dict[str, Any]:
    return json.loads(FACTS.read_text(encoding="utf-8"))


def input_name(name: str) -> str:
    return name.replace("-", "_")


def node(param: dict[str, Any], data: dict[str, Any], op: dict[str, Any]) -> dict[str, Any]:
    """What a step input accepts, from what the documentation says of the parameter."""
    name, kind = param["name"], param["type"].lower()
    required = param["required"]
    limits = data["limits"]
    out: dict[str, Any] = {"required": required}
    if param["in"] == "path":
        out.update(kind="id")
        if name == "threads-user-id":
            out.update(allow_me=True, default_value="me", required=False)
        return out
    if kind == "boolean":
        out["kind"] = "boolean"
    elif kind == "int":
        out["kind"] = "integer"
        if param.get("range"):
            out.update(minimum=param["range"][0], maximum=param["range"][1])
        elif param.get("default_and_maximum"):
            out.update(minimum=0, maximum=param["default_and_maximum"][1])
    elif kind == "float":
        out["kind"] = "decimal"
    elif kind == "datetime":
        out["kind"] = "moment"
        earliest = param.get("earliest")
        if op["path"] == "/{threads-user-id}/threads_insights":
            earliest = data["user_insights"]["earliest"]
        if earliest:
            out["minimum"] = earliest
    elif kind == "url string":
        out["kind"] = "url"
    elif kind == "numeric string":
        out["kind"] = "id"
    elif kind == "list of numeric strings":
        out.update(
            kind="id_list",
            min_items=limits["carousel_min_children"],
            max_items=limits["carousel_max_children"],
        )
    elif kind == "list of strings":
        out.update(kind="codes", max_items=250)
    elif kind == "object":
        out["kind"] = "object"
    elif name in {"fields", "metric"}:
        out["kind"] = "names"
        if param["values"]:
            out["allowed"] = param["values"]
    else:
        out.update(
            kind="text",
            max_length=TEXT_LIMITS.get(name, 2048 if name in {"before", "after"} else 1000),
        )
        if name in TEXT_LIMITS:
            # Post text may span lines.
            out["multiline"] = True
        if param["values"]:
            out["allowed"] = param["values"]
    return out


def describe(op: dict[str, Any], step: dict[str, Any], entry: dict[str, Any]) -> str:
    summary = re.sub(r"\s*See [^.]+ for more information\.", "", op["summary"]).strip()
    words = [summary.rstrip(".") + "."]
    if entry["paged"]:
        words.append(
            "Returns one page (items and next_after to continue from); with all_pages true it "
            "reads every page until the list ends, the output is full or max_items is reached."
        )
    if step.get("accepted"):
        words.append(
            "Threads processes the container before it can be published: the step returns "
            "processing accepted and the container ID; read its status with Get media container "
            "status and publish it with Publish media container."
        )
        if any(p["name"] == "auto_publish_text" for p in op.get("params", [])):
            words.append(
                "A TEXT container with auto_publish_text true is published by Threads without "
                "the publish step: then processing is completed, applied true and no check."
            )
    if op["path"] == "/oembed":
        words.append("The documentation calls it without an access token; none is sent.")
    if step["permissions"]:
        words.append("Needs " + ", ".join(step["permissions"]) + ".")
    return " ".join(words)


def registry() -> dict[str, Any]:
    data = facts()
    ops: dict[str, Any] = {}
    for op in data["operations"]:
        key = (op["method"], op["path"])
        if key in EXCLUDED:
            continue
        step = STEPS[key]
        params = []
        for param in op["params"]:
            params.append(
                {
                    "name": param["name"],
                    "input": input_name(param["name"]),
                    "in": param["in"],
                    "node": node(param, data, op),
                    "description": param["description"],
                }
            )
        if op["path"] == "/{threads-user-id}/threads_insights":
            ui = data["user_insights"]
            params.append(
                {
                    "name": "breakdown",
                    "input": "breakdown",
                    "in": "query",
                    "node": {
                        "kind": "text",
                        "max_length": 10,
                        "required": False,
                        "allowed": ui["breakdown_values"],
                    },
                    "description": (
                        f"With {ui['breakdown_metric']}: one of "
                        + ", ".join(ui["breakdown_values"])
                        + " (insights guide)."
                    ),
                }
            )
        names = {p["name"] for p in op["params"]}
        fixed = [[k, v] for k, v in op["fixed_query"].items() if "..." not in v]
        page = next((p for p in op["params"] if p["name"] == "limit"), None)
        entry = {
            "title": step["title"],
            "area": step["area"],
            "method": op["method"],
            "path": op["path"],
            "shown": f"{op['method']} {op['path']}",
            "fixed_query": fixed,
            "token": op["token_documented"],
            "kind": "read" if op["method"] == "GET" else "write",
            "write_class": step.get("write_class"),
            "processing": {
                "accepted": bool(step.get("accepted")),
                "check": "get_media_container_status" if step.get("accepted") else None,
            },
            "paged": "after" in names,
            "page_size": page["default_and_maximum"] if page else None,
            "permissions": step["permissions"],
            "params": params,
            "page": op["page"],
        }
        entry["description"] = describe(op, step, entry)
        ops[step["id"]] = entry
    pages = data["source"]["pages"]
    return {
        "source": {
            "site": data["source"]["site"],
            "downloaded": data["source"]["downloaded"],
            "api_version": data["limits"]["api_version"],
            "pages": len(pages),
            "facts_sha256": hashlib.sha256(FACTS.read_bytes()).hexdigest(),
        },
        "operations": dict(sorted(ops.items(), key=lambda kv: (AREAS.index(kv[1]["area"]), kv[0]))),
    }


